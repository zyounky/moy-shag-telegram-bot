def sessions_for(action, per_day, *, future=False):
    if action.minutes <= per_day:
        return [{"minutes": action.minutes, "title": action.title, "instruction": action.instruction}]
    parts = PARTS.get(action.artifact, ())
    if future and action.artifact == "attributed_finances":
        parts = (
            (15, "Подготовьте форму будущего учёта", "Создайте колонки для дат кампании, рекламных расходов, связанных продаж и переменных затрат. Не заполняйте исторические пробелы выдуманными суммами."),
            (10, "Выберите источники и способ атрибуции", "Укажите, откуда будете брать каждую цифру и как свяжете будущую продажу с кампанией. До появления данных расчёт не выполняйте."),
        )
    if (not parts or sum(part[0] for part in parts) != action.minutes
            or any(part[0] > per_day for part in parts)):
        return []
    return [{"minutes": minutes, "title": title, "instruction": instruction}
            for minutes, title, instruction in parts]


def schedule(steps):
    total = sum(len(step["sessions"]) for step in steps)
    position = 0
    for index, step in enumerate(steps):
        for session in step["sessions"]:
            session["day"] = 1 + (position * 6 // (total - 1) if total > 1 else 0)
            position += 1
        step.update(id=str(index + 1), day=step["sessions"][0]["day"],
                    day_end=step["sessions"][-1]["day"])
